"""Embed the standalone dashboard as deterministic gzip in ESP32 Flash."""
from pathlib import Path
import gzip

if "__file__" in globals():
    root = Path(__file__).resolve().parent.parent
else:
    Import("env")
    root = Path(env.subst("$PROJECT_DIR"))
source = (root / 'web/index.html').read_bytes()
compressed = gzip.compress(source, compresslevel=9, mtime=0)
rows = ['    '+', '.join(f'0x{byte:02x}' for byte in compressed[start:start+16])+','
        for start in range(0,len(compressed),16)]
header = ('// Generated by scripts/embed_web.py from web/index.html; edit the HTML source.\n'
          '#pragma once\n#include <Arduino.h>\n\n'
          'namespace webdashboard {\n'
          'static const unsigned char PAGE_GZIP[] PROGMEM = {\n'+ '\n'.join(rows)+'\n};\n'
          'constexpr size_t PAGE_GZIP_SIZE = sizeof(PAGE_GZIP);\n}\n')
target=root/'include/web_dashboard.h'
if not target.exists() or target.read_text()!=header:
    target.write_text(header)
print(f'Web dashboard: {len(source)} -> {len(compressed)} bytes gzip (Flash)')
